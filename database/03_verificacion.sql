SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') AS ESQUEMA_ACTUAL FROM DUAL;
SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME IN ('CATEGORIAS', 'TEMAS', 'COMENTARIOS') ORDER BY TABLE_NAME;
SELECT 'CATEGORIAS' AS TABLA, COUNT(*) AS CANTIDAD FROM CATEGORIAS
UNION ALL SELECT 'TEMAS', COUNT(*) FROM TEMAS
UNION ALL SELECT 'COMENTARIOS', COUNT(*) FROM COMENTARIOS;
SELECT ID, NOMBRE FROM CATEGORIAS ORDER BY ID;
SELECT ID, TITULO, CATEGORIA_ID, AUTOR_ID, FECHA_CREACION FROM TEMAS ORDER BY ID;
SELECT ID, TEMA_ID, AUTOR_ID, LENGTH(CONTENIDO) AS LARGO, FECHA_CREACION FROM COMENTARIOS ORDER BY ID;
SELECT COUNT(*) AS TEMAS_HUERFANOS FROM TEMAS T LEFT JOIN CATEGORIAS C ON C.ID = T.CATEGORIA_ID WHERE C.ID IS NULL;
SELECT COUNT(*) AS COMENTARIOS_HUERFANOS FROM COMENTARIOS C LEFT JOIN TEMAS T ON T.ID = C.TEMA_ID WHERE T.ID IS NULL;
SELECT CONSTRAINT_NAME, TABLE_NAME, CONSTRAINT_TYPE, DELETE_RULE, STATUS, VALIDATED
FROM USER_CONSTRAINTS WHERE TABLE_NAME IN ('CATEGORIAS', 'TEMAS', 'COMENTARIOS') ORDER BY TABLE_NAME, CONSTRAINT_NAME;
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHAR_LENGTH, CHAR_USED, NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME IN ('CATEGORIAS', 'TEMAS', 'COMENTARIOS') ORDER BY TABLE_NAME, COLUMN_ID;
-- Ejemplo de búsqueda literal: 100%_ no usa comodines aportados por el usuario.
SELECT ID, TITULO FROM TEMAS
WHERE LOWER(TITULO) LIKE '%100!%!_%' ESCAPE '!' OR LOWER(CONTENIDO) LIKE '%100!%!_%' ESCAPE '!'
ORDER BY FECHA_CREACION DESC, ID DESC;
-- Búsqueda con acentos; verificar además por HTTP las combinaciones con categoría.
SELECT ID, TITULO FROM TEMAS
WHERE LOWER(TITULO) LIKE '%programación%' OR LOWER(CONTENIDO) LIKE '%programación%'
ORDER BY FECHA_CREACION DESC, ID DESC;

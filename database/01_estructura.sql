-- Ejecutar en el esquema Oracle exclusivo de foro-contenido.
-- No elimina tablas ni accede al esquema de usuarios.
CREATE TABLE CATEGORIAS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CLAVE_NOMBRE VARCHAR2(300 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    CONSTRAINT UK_CATEGORIAS_CLAVE UNIQUE (CLAVE_NOMBRE)
);

-- CLAVE_NOMBRE es interna: nombre sin espacios exteriores y en mayúsculas
-- con Locale.ROOT en la aplicación. Mantener la misma clave en cargas SQL.

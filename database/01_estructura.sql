-- Ejecutar en el esquema Oracle exclusivo de foro-contenido.
-- No elimina tablas ni accede al esquema de usuarios.
CREATE TABLE CATEGORIAS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100 CHAR) NOT NULL,
    CLAVE_NOMBRE VARCHAR2(300 CHAR) NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    CONSTRAINT UK_CATEGORIAS_CLAVE UNIQUE (CLAVE_NOMBRE)
);

-- CLAVE_NOMBRE es interna: nombre sin espacios exteriores y en mayúsculas
-- con Locale.ROOT en la aplicación. Mantener la misma clave en cargas SQL.

CREATE TABLE TEMAS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO VARCHAR2(200 CHAR) NOT NULL,
    CONTENIDO CLOB NOT NULL,
    CATEGORIA_ID NUMBER(19) NOT NULL,
    AUTOR_ID NUMBER(19) NOT NULL,
    FECHA_CREACION TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT CK_TEMAS_AUTOR CHECK (AUTOR_ID > 0),
    CONSTRAINT FK_TEMAS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID)
);
CREATE INDEX IX_TEMAS_CATEGORIA ON TEMAS(CATEGORIA_ID);

-- AUTOR_ID proviene de identidad HTTP: no existe FK entre esquemas/servicios.

CREATE TABLE COMENTARIOS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENIDO CLOB NOT NULL,
    TEMA_ID NUMBER(19) NOT NULL,
    AUTOR_ID NUMBER(19) NOT NULL,
    FECHA_CREACION TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT CK_COMENTARIOS_AUTOR CHECK (AUTOR_ID > 0),
    CONSTRAINT FK_COMENTARIOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMAS(ID) ON DELETE CASCADE
);
CREATE INDEX IX_COMENTARIOS_TEMA ON COMENTARIOS(TEMA_ID);
